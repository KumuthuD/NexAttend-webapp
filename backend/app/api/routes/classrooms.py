#  GET /classrooms/     List classrooms

@router.get("/", response_model=List[ClassroomResponse])
async def list_classrooms(
    db=Depends(get_database),
    current_user: User = Depends(get_current_user),
):
    """
    - Teachers see only their own classrooms.
    - Students see only classrooms they have joined.
    """
    user_id = str(current_user.id)

    if current_user.role == "teacher":
        classrooms = await db["classrooms"].find(
            {"teacher_id": user_id}
        ).to_list(200)
    else:
        # Student: find classrooms where their id is in student_ids
        classrooms = await db["classrooms"].find(
            {"student_ids": user_id}
        ).to_list(200)

    response = []
    for cls in classrooms:
        response.append(
            ClassroomResponse(
                **cls,
                student_count=len(cls.get("student_ids", [])),
            )
        )
    return response



#  POST /classrooms/        Create classroom (teacher only)

@router.post("/", response_model=ClassroomResponse, status_code=status.HTTP_201_CREATED)
async def create_classroom(
    classroom_in: ClassroomCreate,
    db=Depends(get_database),
    current_user: User = Depends(get_current_user),
):
    """
    Teacher creates a new classroom.
    An access code is automatically generated and saved.
    """
    if current_user.role != "teacher":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only teachers can create classrooms",
        )

    # Build the classroom model — access_code auto-generated by the model
    classroom = Classroom(
        name=classroom_in.name,
        course_code=classroom_in.course_code,
        description=classroom_in.description,
        schedule=classroom_in.schedule,
        teacher_id=str(current_user.id),
    )

    classroom_dict = classroom.model_dump(by_alias=True)
    await db["classrooms"].insert_one(classroom_dict)

    created = await db["classrooms"].find_one({"_id": classroom.id})
    if not created:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to create classroom",
        )

    logger.info(
        f"Classroom '{classroom.name}' created by teacher {current_user.id} "
        f"with access code {classroom.access_code}"
    )

    # Trigger notification
    notification = Notification(
        user_id=str(current_user.id),
        title="Classroom Created",
        message=f"You successfully created the classroom '{classroom.name}'.",
        type="success"
    )
    await db["notifications"].insert_one(notification.model_dump(by_alias=True, exclude_none=True))

    return ClassroomResponse(
        **created,
        student_count=0,
    )


#  POST /classrooms/join    Student joins via access code

@router.post("/join", response_model=JoinClassroomResponse)
async def join_classroom(
    join_in: JoinClassroomRequest,
    db=Depends(get_database),
    current_user: User = Depends(get_current_user),
):
    """
    Student provides an access code to join the matching classroom.
    The student's user ID is added to classroom.student_ids.
    """
    if current_user.role != "student":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only students can join classrooms",
        )

    user_id = str(current_user.id)
    access_code = join_in.access_code.strip().upper()

    # 1. Find the classroom by access code
    classroom = await db["classrooms"].find_one({"access_code": access_code})
    if not classroom:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Invalid access code. No classroom found.",
        )

    classroom_id = str(classroom["_id"])

    # 2. Check if student is already enrolled
    if user_id in classroom.get("student_ids", []):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="You have already joined this classroom.",
        )

    # 3. Add student to the classroom
    result = await db["classrooms"].update_one(
        {"_id": classroom_id},
        {"$addToSet": {"student_ids": user_id}},
    )

    if result.modified_count == 0:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to join classroom. Please try again.",
        )

    logger.info(
        f"Student {user_id} joined classroom '{classroom['name']}' "
        f"(id={classroom_id}) via access code {access_code}"
    )

    # Trigger notification
    notification = Notification(
        user_id=user_id,
        title="Joined Classroom",
        message=f"You successfully joined the classroom '{classroom['name']}'.",
        type="success"
    )
    await db["notifications"].insert_one(notification.model_dump(by_alias=True, exclude_none=True))

    # Trigger email
    if current_user.email:
        asyncio.create_task(
            email_service.send_class_join_confirmation(
                email=current_user.email,
                student_name=current_user.full_name or "Student",
                class_name=classroom["name"],
                date_time=datetime.utcnow()
            )
        )

    return JoinClassroomResponse(
        message=f"Successfully joined '{classroom['name']}'!",
        classroom_id=classroom_id,
        classroom_name=classroom["name"],
    )



